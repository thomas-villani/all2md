"""Load the committed corpus and refuse anything that does not match the manifest.

CI-safe: no COM, no Word, no network. The corpus bytes are committed, so loading is
just verification -- but verification is the whole point. A truth record that has
drifted away from its document is worse than no corpus at all, because it produces
confident numbers about a document nobody described.

So the manifest pins **both** halves: the ``.docx`` digest and the digest of the
expected-facts file beside it. Neither can move without the other being re-recorded.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
MANIFEST = HERE / "manifest.json"

MANIFEST_SCHEMA_VERSION = 1
_SHA256 = re.compile(r"^[0-9a-f]{64}$")
_CASE_KEYS = {
    "case_id",
    "family",
    "path",
    "sha256",
    "size_bytes",
    "generator",
    "expected_sha256",
    "resave_stable",
    "resave_failures",
}


class CorpusError(RuntimeError):
    """The committed corpus does not match its manifest."""


@dataclass(frozen=True)
class Case:
    """One corpus document and the truth recorded beside it."""

    case_id: str
    family: str
    path: Path
    expected: dict[str, Any]

    @property
    def name(self) -> str:
        return self.case_id.split("/", 1)[1]

    @property
    def is_control(self) -> bool:
        """Controls exercise things that already work.

        A control reported broken is a bug in the lane, not in the parser, so the
        ledger separates them rather than letting a lane fault read as a defect.

        This is declared in the case spec, not inferred from the file name. It was
        inferred at first -- any case whose name ended in ``-control`` -- and
        ``sdt/block-content-control`` promptly tripped it: a defect case whose name
        happens to end in the word "control" was reported as a lane bug.
        """
        return bool(self.expected.get("control", False))

    @property
    def facts(self) -> dict[str, Any]:
        return dict(self.expected.get("facts", {}))


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _validate_entry(entry: Any, index: int) -> dict[str, Any]:
    if not isinstance(entry, dict):
        raise CorpusError(f"manifest case {index} is not an object")
    missing = _CASE_KEYS - set(entry)
    extra = set(entry) - _CASE_KEYS
    if missing or extra:
        raise CorpusError(f"manifest case {index} key mismatch: missing {sorted(missing)}, unexpected {sorted(extra)}")
    for key in ("sha256", "expected_sha256"):
        if not isinstance(entry[key], str) or not _SHA256.match(entry[key]):
            raise CorpusError(f"manifest case {index}: {key} is not a sha256 digest")
    size = entry["size_bytes"]
    # bool is an int in Python; a True here would silently pass an int check.
    if isinstance(size, bool) or not isinstance(size, int) or size <= 0:
        raise CorpusError(f"manifest case {index}: size_bytes must be a positive int")
    if not isinstance(entry["resave_stable"], bool):
        raise CorpusError(f"manifest case {index}: resave_stable must be a bool")
    return entry


def load_corpus(manifest_path: Path | None = None) -> list[Case]:
    """Every case in the manifest, with both digests revalidated."""
    path = manifest_path or MANIFEST
    if not path.exists():
        raise CorpusError(f"no manifest at {path}; the corpus is generated by hand, see generate/README.md")
    manifest = json.loads(path.read_text(encoding="utf-8"))

    version = manifest.get("schema_version")
    if version != MANIFEST_SCHEMA_VERSION:
        raise CorpusError(f"manifest schema {version!r}, expected {MANIFEST_SCHEMA_VERSION}")

    root = path.parent
    cases = []
    for index, entry in enumerate(manifest.get("cases", [])):
        _validate_entry(entry, index)
        document = root / entry["path"]
        if not document.exists():
            raise CorpusError(f"{entry['case_id']}: {document} is missing")
        actual = _digest(document)
        if actual != entry["sha256"]:
            raise CorpusError(
                f"{entry['case_id']}: {document.name} digest {actual[:12]} != manifest {entry['sha256'][:12]}"
            )
        if document.stat().st_size != entry["size_bytes"]:
            raise CorpusError(f"{entry['case_id']}: {document.name} size does not match the manifest")

        family, name = entry["case_id"].split("/", 1)
        expected_path = root / "expected" / family / f"{name}.json"
        if not expected_path.exists():
            raise CorpusError(f"{entry['case_id']}: no truth record at {expected_path}")
        if _digest(expected_path) != entry["expected_sha256"]:
            raise CorpusError(
                f"{entry['case_id']}: the truth record has changed without the manifest being re-recorded"
            )

        cases.append(
            Case(
                case_id=entry["case_id"],
                family=family,
                path=document,
                expected=json.loads(expected_path.read_text(encoding="utf-8")),
            )
        )

    if not cases:
        raise CorpusError("the manifest names no cases")
    return cases


def provenance(manifest_path: Path | None = None) -> dict[str, Any]:
    """How the corpus was produced -- Word build, wordlive version, pinned author."""
    path = manifest_path or MANIFEST
    manifest = json.loads(path.read_text(encoding="utf-8"))
    return dict(manifest.get("provenance", {}))
